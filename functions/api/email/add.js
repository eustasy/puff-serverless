import { verifySession } from "../../../src/session_auth.js";
import { addEmail } from "../../../src/emails.js";

export async function onRequestPost(context) {
  let user_uuid;
  try {
    const sessionResult = await verifySession(context.request.headers.get("Authorization")?.split(" ")[1]);

    if (sessionResult.error) {
      return new Response(JSON.stringify({ error: sessionResult.error }), 
        { status: sessionResult.status || 401, headers: { "Content-Type": "application/json" } });
    }
    user_uuid = sessionResult.user_uuid;
  } catch (e) {
    console.error("Session verification error:", e);
    return new Response(JSON.stringify({ error: "Session verification failed." }), 
      { status: 401, headers: { "Content-Type": "application/json" } });
  }

  let requestBody;
  try {
    requestBody = await context.request.json();
  } catch (e) {
    return new Response(JSON.stringify({ error: "Invalid JSON body." }), 
      { status: 400, headers: { "Content-Type": "application/json" } });
  }

  const { email_address } = requestBody;

  if (!email_address || typeof email_address !== "string" || !email_address.includes("@")) {
    return new Response(JSON.stringify({ error: "Email address is missing or invalid." }),
      { status: 400, headers: { "Content-Type": "application/json" } });
  }

  try {
    // Call the centralized addEmail function from src/emails.js
    // For adding a backup email, is_primary is false, and is_verified is false initially.
    const result = await addEmail(context, user_uuid, email_address, false, false);

    if (result.error) {
      return new Response(JSON.stringify({ error: result.message }), 
        { status: result.status || 500, headers: { "Content-Type": "application/json" } });
    }

    // If successful, a verification token would have been generated by addEmail and logged.
    // The actual email sending should be handled separately (e.g., by a transactional email service).
    return new Response(JSON.stringify({
        message: "Email added. A verification link has been generated (see server logs).", 
        token: result.token_value // Optionally return the token for testing/dev
    }), { status: 200, headers: { "Content-Type": "application/json" } });

  } catch (error) {
    console.error("Error in add email endpoint:", error);
    // Handle potential unique constraint violation if email is already in use by another account globally
    // This might be caught by addEmail itself if it has a global check, or here if not.
    if (error.message && error.message.includes("already in use")) { // Generic check
        return new Response(JSON.stringify({ error: "This email address is already in use." }),
            { status: 409, headers: { "Content-Type": "application/json" } });
    }
    return new Response(JSON.stringify({ error: "Failed to add email due to a server error." }),
      { status: 500, headers: { "Content-Type": "application/json" } });
  }
}

export async function onRequest(context) {
  if (context.request.method === "POST") {
    return await onRequestPost(context);
  }
  return new Response(JSON.stringify({ error: "Method Not Allowed" }), {
    status: 405,
    headers: { "Allow": "POST", "Content-Type": "application/json" },
  });
}
